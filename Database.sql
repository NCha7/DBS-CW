-- Targeted DBMS: MySQL / LiveSQL

-- =============================================
-- Part 1: Schema Creation
-- =============================================

-- 1. COUNTRY
CREATE TABLE COUNTRY (
    COUNTRY_ID      INT PRIMARY KEY,
    NAME            VARCHAR(100) NOT NULL UNIQUE,
    REGION          VARCHAR(50)  NOT NULL,
    POPULATION      BIGINT       NOT NULL,
    GDP_PER_CAPITA  DECIMAL(12,2),
    IS_DEVELOPING   BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT CHK_POPULATION CHECK (POPULATION > 0)
);

-- 2. COP_EVENT
CREATE TABLE COP_EVENT (
    EVENT_ID        INT PRIMARY KEY,
    NAME            VARCHAR(50)  NOT NULL UNIQUE,
    LOCATION        VARCHAR(100) NOT NULL,
    START_DATE      DATE         NOT NULL,
    END_DATE        DATE         NOT NULL,
    HOST_COUNTRY_ID INT          NOT NULL,
    CONSTRAINT FK_HOST_COUNTRY FOREIGN KEY (HOST_COUNTRY_ID) REFERENCES COUNTRY(COUNTRY_ID),
    CONSTRAINT CHK_DATES CHECK (END_DATE >= START_DATE)
);

-- 3. ISSUE
CREATE TABLE ISSUE (
    ISSUE_ID        INT PRIMARY KEY,
    TITLE           VARCHAR(150) NOT NULL UNIQUE,
    DESCRIPTION     TEXT,
    PRIORITY_LEVEL  INT          NOT NULL,
    CONSTRAINT CHK_PRIORITY CHECK (PRIORITY_LEVEL BETWEEN 1 AND 5)
);

-- 4. COMMUNITY
CREATE TABLE COMMUNITY (
    COMMUNITY_ID        INT PRIMARY KEY,
    NAME                VARCHAR(100) NOT NULL,
    COUNTRY_ID          INT          NOT NULL,
    POPULATION          INT          NOT NULL,
    VULNERABILITY_SCORE DECIMAL(3,1) NOT NULL,
    IS_DISADVANTAGED    BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT FK_COMMUNITY_COUNTRY FOREIGN KEY (COUNTRY_ID) REFERENCES COUNTRY(COUNTRY_ID),
    CONSTRAINT CHK_VULN_SCORE CHECK (VULNERABILITY_SCORE BETWEEN 0 AND 10),
    CONSTRAINT CHK_COMM_POP CHECK (POPULATION > 0)
);

-- 5. CLIMATE_MEASUREMENT
CREATE TABLE CLIMATE_MEASUREMENT (
    MEASUREMENT_ID   INT PRIMARY KEY,
    COMMUNITY_ID     INT           NOT NULL,
    MEASUREMENT_TYPE VARCHAR(50)   NOT NULL,
    VALUE            DECIMAL(10,2) NOT NULL,
    UNIT             VARCHAR(20)   NOT NULL,
    MEASURED_DATE    DATE          NOT NULL,
    CONSTRAINT FK_MEAS_COMMUNITY FOREIGN KEY (COMMUNITY_ID) REFERENCES COMMUNITY(COMMUNITY_ID),
    CONSTRAINT CHK_MEAS_TYPE CHECK (MEASUREMENT_TYPE IN ('temperature','air_quality','river_pollution','sea_level'))
);

-- 6. ACTION (SUPERCLASS)
CREATE TABLE ACTION (
    ACTION_ID     INT PRIMARY KEY,
    TITLE         VARCHAR(150) NOT NULL,
    COUNTRY_ID    INT          NOT NULL,
    COMMUNITY_ID  INT,
    START_DATE    DATE         NOT NULL,
    STATUS        VARCHAR(20)  NOT NULL,
    BUDGET_USD    DECIMAL(15,2),
    ACTION_TYPE   VARCHAR(30)  NOT NULL,
    CONSTRAINT FK_ACTION_COUNTRY   FOREIGN KEY (COUNTRY_ID)   REFERENCES COUNTRY(COUNTRY_ID),
    CONSTRAINT FK_ACTION_COMMUNITY FOREIGN KEY (COMMUNITY_ID) REFERENCES COMMUNITY(COMMUNITY_ID),
    CONSTRAINT CHK_STATUS CHECK (STATUS IN ('Planned','Ongoing','Completed')),
    CONSTRAINT CHK_ACTION_TYPE CHECK (ACTION_TYPE IN ('Energy','Adaptation'))
);

-- 7. ENERGY_ACTION (SUBCLASS of ACTION)
CREATE TABLE ENERGY_ACTION (
    ACTION_ID              INT PRIMARY KEY,
    ENERGY_TYPE            VARCHAR(50)   NOT NULL,
    CAPACITY_MW            DECIMAL(10,2),
    EMISSIONS_SAVED_TONNES DECIMAL(12,2),
    CONSTRAINT FK_ENERGY_ACTION FOREIGN KEY (ACTION_ID) REFERENCES ACTION(ACTION_ID)
        ON DELETE CASCADE
);

-- 8. ADAPTATION_ACTION (SUBCLASS of ACTION)
CREATE TABLE ADAPTATION_ACTION (
    ACTION_ID         INT PRIMARY KEY,
    ADAPTATION_TYPE   VARCHAR(50) NOT NULL,
    PEOPLE_PROTECTED  INT,
    CONSTRAINT FK_ADAPT_ACTION FOREIGN KEY (ACTION_ID) REFERENCES ACTION(ACTION_ID)
        ON DELETE CASCADE,
    CONSTRAINT CHK_PEOPLE CHECK (PEOPLE_PROTECTED >= 0)
);
